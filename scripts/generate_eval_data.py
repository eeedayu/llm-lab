def write_jsonl(relative_path, rows):
    path = ROOT / relative_path
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Wrote {len(rows)} rows: {path}")


def build_cpt():
    rows = []
    for topic, fact, action, caveat, check in CPT_NOTES:
        rows.append({
            "text": (
                f"{topic}会影响领域语料的可用性。{fact}{action}"
                f"{caveat}{check}"
            )
        })
        rows.append({
            "text": (
                f"处理{topic}时，应把来源与转换过程纳入数据记录。{fact}"
                f"{action}{check}如果发现无法验证的关键内容，应隔离样本并记录原因。"
            )
        })
        rows.append({
            "text": (
                f"在训练数据审核中，{topic}需要单独设立检查项。{caveat}"
                f"{action}完成处理后，{check}"
            )
        })
        rows.append({
            "text": (
                f"构建可复现的领域数据集时，{topic}不能只靠文件格式校验。"
                f"{fact}{check}{action}最终应保留可追溯的处理记录。"
            )
        })
    return rows


def build_sft():
    return [
        {"messages": [
            {"role": "user", "content": question},
            {"role": "assistant", "content": answer},
        ]}
        for question, answer in SFT_QA
    ]


def build_dpo():
    return [
        {
            "prompt": [{"role": "user", "content": prompt}],
            "chosen": [{"role": "assistant", "content": chosen}],
            "rejected": [{"role": "assistant", "content": rejected}],
        }
        for prompt, chosen, rejected in DPO_PAIRS
    ]


if __name__ == "__main__":
    datasets = {
        "cpt": build_cpt(),
        "sft": build_sft(),
        "dpo": build_dpo(),
    }
    expected = {"cpt": 100, "sft": 50, "dpo": 30}
    for name, rows in datasets.items():
        assert len(rows) == expected[name], f"{name}: expected {expected[name]}, got {len(rows)}"
        assert len({json.dumps(row, ensure_ascii=False, sort_keys=True) for row in rows}) == len(rows), (
            f"{name}: duplicate rows"
        )
        write_jsonl(f"data/{name}/eval.jsonl", rows)
