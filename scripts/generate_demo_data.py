def write_jsonl(relative_path, rows):
    path = ROOT / relative_path
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Wrote {len(rows)} rows: {path}")


def build_cpt():
    rows = []
    count_per_topic, extra_topics = divmod(1000, len(CPT_TOPICS))
    for topic_index, (title, why, action, caution, check) in enumerate(CPT_TOPICS):
        topic_count = count_per_topic + (topic_index < extra_topics)
        for offset in range(topic_count):
            stage, context = CPT_CONTEXTS[(topic_index + offset) % len(CPT_CONTEXTS)]
            text = (
                f"{title}是大模型微调数据与训练流程中的重要环节。{why}。"
                f"在{stage}阶段，{context}。{action}。{caution}。"
                f"完成后，{check}。团队还应把判断依据和处理结果记入实验记录，"
                "使下一次训练能够复核同一决策，而不是依赖无法追溯的临时操作。"
            )
            rows.append({"text": text})
    return rows


def build_sft():
    rows = []
    for question, answer in SFT_QA:
        for prefix in PROMPT_PREFIXES:
            rows.append({
                "messages": [
                    {"role": "user", "content": prefix + question},
                    {"role": "assistant", "content": answer},
                ]
            })
    return rows[:500]


def build_dpo():
    rows = []
    for prompt, chosen, rejected in DPO_PAIRS:
        for form in DPO_PROMPT_FORMS:
            rows.append({
                "prompt": [{"role": "user", "content": form.format(prompt)}],
                "chosen": [{"role": "assistant", "content": chosen}],
                "rejected": [{"role": "assistant", "content": rejected}],
            })
    return rows[:300]


if __name__ == "__main__":
    write_jsonl("data/cpt/train.jsonl", build_cpt())
    write_jsonl("data/sft/train.jsonl", build_sft())
    write_jsonl("data/dpo/train.jsonl", build_dpo())
